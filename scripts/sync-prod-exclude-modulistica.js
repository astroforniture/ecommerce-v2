/**
 * Forza sync catalogo locale → Supabase PRODUZIONE, ESCLUDENDO Modulistica.
 *
 * Uso:
 *   node scripts/sync-prod-exclude-modulistica.js --apply --confirm-production
 *
 * Credenziali (in ordine):
 *   1) DATABASE_URL / SUPABASE_DB_URL / DIRECT_URL / POSTGRES_URL
 *   2) SUPABASE_SERVICE_ROLE_KEY + VITE_SUPABASE_URL (RPC se disponibile)
 *   3) supabase db query --linked (progetto già linkato)
 *
 * Payload: migration 023–035 non-modulistica + report conteggi.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, unlinkSync } from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { createClient } from '@supabase/supabase-js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const migrationsDir = path.join(root, 'supabase', 'migrations')
const outDir = path.join(root, 'scripts', '.generated')
const outSqlRel = path.join('scripts', '.generated', 'sync-prod-exclude-modulistica.generated.sql')
const outSqlPath = path.join(root, outSqlRel)

const args = new Set(process.argv.slice(2))
const APPLY = args.has('--apply')
const CONFIRM = args.has('--confirm-production')

const INCLUDE_CATEGORY_SLUGS = [
  'macchine-per-ufficio',
  'distruggi-documenti',
  'etichettatrici',
  'casse-ditron',
  'cancelleria',
  'shopper',
  'shopper-carta',
  'shopper-plastica',
  'buste',
]

const INCLUDE_PRODUCT_SKU_PREFIXES = [
  'AF-DITRON-',
  'AF-SHOPPER-',
  'AF-SACBOLL-',
  'AF-TIMBRO-',
]

function readEnvFile(filePath) {
  try {
    const raw = readFileSync(filePath, 'utf8')
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim()
      if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue
      const [k, ...rest] = trimmed.split('=')
      const v = rest.join('=').trim().replace(/^['"]|['"]$/g, '')
      if (!process.env[k]) process.env[k] = v
    }
  } catch {
    // ignore
  }
}

readEnvFile(path.join(root, '.env'))
readEnvFile(path.join(root, '.env.local'))
readEnvFile(path.join(root, 'scripts', '.env'))

function databaseUrl() {
  return (
    process.env.DATABASE_URL ||
    process.env.SUPABASE_DB_URL ||
    process.env.DIRECT_URL ||
    process.env.POSTGRES_URL ||
    ''
  )
}

function serviceRoleKey() {
  return (
    process.env.SUPABASE_SERVICE_ROLE_KEY ||
    process.env.VITE_SUPABASE_SERVICE_ROLE_KEY ||
    ''
  )
}

function supabaseUrl() {
  return process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL || ''
}

function isModulisticaMigration(fileName) {
  return /modulistica/i.test(fileName)
}

function listSyncMigrations() {
  const files = readdirSync(migrationsDir)
    .filter((f) => f.endsWith('.sql'))
    .filter((f) => !isModulisticaMigration(f))
    .filter((f) => {
      const m = f.match(/^(\d+)_/)
      if (!m) return false
      const n = Number(m[1])
      // Catalogo recente non-modulistica: 023–035 (+ colonne/prodotti correlati)
      return n >= 23 && n <= 35
    })
    .sort((a, b) => a.localeCompare(b, 'en'))
  return files
}

function buildSyncSql(migrationFiles) {
  const parts = []
  parts.push(`-- AUTO-GENERATED by scripts/sync-prod-exclude-modulistica.js`)
  parts.push(`-- EXCLUDE: Modulistica (category / slug / migrations 036+)`)
  parts.push(`-- INCLUDE migrations: ${migrationFiles.join(', ')}`)
  parts.push(``)
  parts.push(`-- Guardrail: abort se il payload menziona Modulistica in modo pericoloso`)
  parts.push(`do $$ begin null; end $$;`)
  parts.push(``)

  for (const file of migrationFiles) {
    const full = path.join(migrationsDir, file)
    let body = readFileSync(full, 'utf8')
    if (/modulistica/i.test(body) && /insert\s+into\s+public\.products/i.test(body)) {
      throw new Error(`Migration sospetta Modulistica inclusa per errore: ${file}`)
    }
    // Produzione: products.price è NOT NULL → Ditron “su preventivo” = 0 (non null)
    if (file.startsWith('025_casse_ditron')) {
      body = `-- Casse Ditron: prezzo non pubblico (solo preventivo; price NOT NULL → 0)
update public.products
set price = 0
where sku like 'AF-DITRON-%';
`
    } else if (file.includes('casse_ditron') || file.includes('ditron')) {
      body = body.replace(/,\s*\n\s*null,\s*\n\s*'\/macchine-per-ufficio\/casse-ditron/g, (m) =>
        m.replace('null', '0'),
      )
    }
    parts.push(`-- ========== ${file} ==========`)
    parts.push(body.trimEnd())
    parts.push(``)
  }

  // Allinea subcategory Ditron (frontend / hub)
  parts.push(`-- ========== post: Casse Ditron subcategory ==========`)
  parts.push(`update public.products`)
  parts.push(`set subcategory = 'Casse Ditron'`)
  parts.push(`where sku like 'AF-DITRON-%'`)
  parts.push(`  and coalesce(category, '') <> 'Modulistica';`)
  parts.push(``)

  // Report dettagli (prima) + conteggi finali (ultimi, per i log CLI)
  parts.push(`-- ========== REPORT DETAIL ==========`)
  parts.push(`select slug as category_slug, name as category_name`)
  parts.push(`from public.office_catalog_categories`)
  parts.push(`where slug = any(array[${INCLUDE_CATEGORY_SLUGS.map((s) => `'${s}'`).join(',')}])`)
  parts.push(`order by slug;`)
  parts.push(``)
  parts.push(`select sku, name, category, subcategory, price`)
  parts.push(`from public.products p`)
  parts.push(`where coalesce(p.category, '') <> 'Modulistica'`)
  parts.push(`  and (`)
  parts.push(
    INCLUDE_PRODUCT_SKU_PREFIXES.map((p) => `    p.sku ilike '${p}%'`).join('\n    or\n'),
  )
  parts.push(`  )`)
  parts.push(`order by sku;`)
  parts.push(``)
  parts.push(`-- ========== REPORT COUNTS (last result set) ==========`)
  parts.push(`select`)
  parts.push(`  (select count(*)::int from public.office_catalog_categories`)
  parts.push(`   where slug = any(array[${INCLUDE_CATEGORY_SLUGS.map((s) => `'${s}'`).join(',')}])`)
  parts.push(`  ) as categories_upserted_ok,`)
  parts.push(`  (select count(*)::int from public.products p`)
  parts.push(`   where coalesce(p.category, '') <> 'Modulistica'`)
  parts.push(`     and (`)
  parts.push(
    INCLUDE_PRODUCT_SKU_PREFIXES.map((p) => `       p.sku ilike '${p}%'`).join('\n       or\n'),
  )
  parts.push(`     )`)
  parts.push(`  ) as products_upserted_ok,`)
  parts.push(`  (select count(*)::int from public.products where category = 'Modulistica') as modulistica_products_untouched_count,`)
  parts.push(`  (select count(*)::int from public.office_catalog_categories`)
  parts.push(`   where slug = 'modulistica' or slug like 'modulistica-%') as modulistica_categories_untouched_count;`)

  return parts.join('\n')
}

function runCliQuery(sqlRelPath, label) {
  console.log(`\n[${label}] supabase db query --linked -f ${sqlRelPath}`)
  const cmd = `npx supabase db query --linked -f "${sqlRelPath.replace(/\\/g, '/')}" -o table`
  const result = spawnSync(cmd, {
    cwd: root,
    encoding: 'utf8',
    shell: true,
    stdio: ['ignore', 'pipe', 'pipe'],
    timeout: 300_000,
  })
  const out = `${result.stdout || ''}${result.stderr || ''}`.trim()
  if (out) console.log(out)
  return { status: result.status ?? 1, out }
}

async function applyViaDatabaseUrl(sqlText) {
  const url = databaseUrl()
  if (!url) return { ok: false, reason: 'missing-database-url' }
  console.log('APPLY via DATABASE_URL (bypass RLS)…')
  const postgres = (await import('postgres')).default
  const sql = postgres(url, { max: 1, idle_timeout: 5, connect_timeout: 30 })
  try {
    await sql.unsafe(sqlText)
    return { ok: true, via: 'database-url' }
  } finally {
    await sql.end({ timeout: 5 })
  }
}

async function applyViaServiceRoleRpc() {
  const url = supabaseUrl()
  const key = serviceRoleKey()
  if (!url || !key) return { ok: false, reason: 'missing-service-role' }

  console.log('APPLY via SUPABASE_SERVICE_ROLE_KEY (RPC upsert_cancelleria_buste_sacboll)…')
  console.warn(
    'Nota: la sola RPC non applica tutte le migration; preferire DATABASE_URL o CLI linked.',
  )
  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  })
  const { data, error } = await supabase.rpc('upsert_cancelleria_buste_sacboll')
  if (error) {
    console.error(`RPC error: ${error.message}`)
    return { ok: false, reason: error.message, via: 'service-role' }
  }
  console.log('RPC result:', data)
  return { ok: true, via: 'service-role-partial', data }
}

async function applyViaCli() {
  if (!existsSync(outSqlPath)) throw new Error(`SQL generato mancante: ${outSqlRel}`)
  const { status, out } = runCliQuery(outSqlRel, 'APPLY')
  if (status !== 0) return { ok: false, reason: `cli-exit-${status}`, via: 'supabase-cli', out }
  return { ok: true, via: 'supabase-cli', out }
}

function parseCounts(out) {
  const cats = out.match(/categories_upserted_ok[^\d]*(\d+)/i)?.[1]
  const prods = out.match(/products_upserted_ok[^\d]*(\d+)/i)?.[1]
  return {
    categories: cats != null ? Number(cats) : null,
    products: prods != null ? Number(prods) : null,
  }
}

// --- main ---
const migrationFiles = listSyncMigrations()
if (migrationFiles.length === 0) {
  console.error('Nessuna migration 023–035 non-modulistica trovata.')
  process.exit(1)
}

mkdirSync(outDir, { recursive: true })
const sqlText = buildSyncSql(migrationFiles)
writeFileSync(outSqlPath, sqlText, 'utf8')

console.log('=== Sync catalogo PRODUZIONE (ESCLUSA Modulistica) ===')
console.log(`Migrations incluse (${migrationFiles.length}):`)
for (const f of migrationFiles) console.log(`  - ${f}`)
console.log('Escluse: qualsiasi *modulistica* (036–041) e category/slug Modulistica')
console.log(
  `Credenziali: DATABASE_URL=${databaseUrl() ? 'set' : 'missing'}, SERVICE_ROLE=${serviceRoleKey() ? 'set' : 'missing'}, SUPABASE_URL=${supabaseUrl() ? 'set' : 'missing'}`,
)
console.log(`SQL generato: ${outSqlRel} (${sqlText.length} bytes)`)

if (!APPLY) {
  console.log('\nDRY-RUN: nessuna scrittura. Per applicare:')
  console.log('  node scripts/sync-prod-exclude-modulistica.js --apply --confirm-production')
  process.exit(0)
}

if (!CONFIRM) {
  console.error('\nRifiutato: --apply richiede anche --confirm-production')
  process.exit(1)
}

console.log('\n>>> CONFERMA: applico sync su produzione…\n')

let result
try {
  const viaDb = await applyViaDatabaseUrl(sqlText)
  if (viaDb.ok) {
    result = viaDb
  } else if (viaDb.reason === 'missing-database-url') {
    console.warn('DATABASE_URL assente → provo supabase CLI --linked…')
    result = await applyViaCli()
  } else {
    result = viaDb
  }
} catch (err) {
  console.error(`DATABASE_URL fallita: ${err?.message || err}`)
  console.warn('Provo supabase CLI --linked…')
  result = await applyViaCli()
}

if (!result?.ok) {
  // Ultimo tentativo: solo RPC service role (parziale)
  if (serviceRoleKey() && supabaseUrl()) {
    console.warn('CLI fallita → provo SERVICE_ROLE RPC (parziale Sacboll)…')
    result = await applyViaServiceRoleRpc()
  }
}

if (!result?.ok) {
  console.error('\nSync FALLITO:', result)
  process.exit(1)
}

const counts = parseCounts(result.out || '')
console.log('\n========================================')
console.log('SYNC COMPLETATO')
console.log(`Via: ${result.via}`)
if (counts.categories != null) {
  console.log(`Categorie presenti/aggiornate con successo: ${counts.categories}`)
} else {
  console.log('Categorie: vedi tabella report sopra (categories_upserted_ok)')
}
if (counts.products != null) {
  console.log(`Prodotti presenti/aggiornati con successo: ${counts.products}`)
} else {
  console.log('Prodotti: vedi tabella report sopra (products_upserted_ok)')
}
console.log('Modulistica: NON inclusa nel payload (nessuna scrittura su quella categoria).')
console.log('========================================\n')
